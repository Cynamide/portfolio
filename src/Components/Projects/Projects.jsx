import React, { useEffect, useState } from "react";
import { Card, Button, Modal } from "antd";
import * as tf from "@tensorflow/tfjs";
import "./Projects.css";

const projects = [
  { title: "LocalEval", url: "https://github.com/Cynamide/go-exec-sandbox", description: "A benchmark workbench for comparing models on coding tasks. It runs generated code in isolated Docker containers and records results and evidence for each run.", stack: "Go · Next.js · Docker · PostgreSQL" },
  { title: "RAGFlow", url: "https://github.com/Cynamide/llm-context-chatbot", description: "A document chatbot that lets you upload files and ask questions grounded in their content. It retrieves relevant passages and streams answers to the interface.", stack: "Next.js · Cloudflare Workers · LangChain", demo: "https://llm-context-chatbot.vercel.app" },
  { title: "LLM on Call", url: "https://github.com/Cynamide/llm-on-call", description: "A voice agent with a FastAPI backend, a Twilio call flow, and real-time audio through Ultravox.", stack: "Python · FastAPI · Twilio · Ultravox" },
  { title: "Customer Detection", url: "https://github.com/Cynamide/customer_detection", description: "A computer vision system that detects and tracks people interacting with products in video. Built for the Tractor Supply AI/ML Hackathon.", stack: "TensorFlow · YOLOv4 · DeepSORT", action: "customer" },
  { title: "RL Games", url: "https://github.com/Cynamide/RL_Games", description: "A reinforcement learning agent built for the IIT Madras Shaastra hackathon, where I finished second. The agent combines deep Q-learning and minimax.", stack: "TensorFlow · OpenAI Gym · Matplotlib", action: "rl" },
  { title: "WGAN-GP", url: "https://github.com/Cynamide/GAN/", description: "A TensorFlow implementation of a Wasserstein GAN with gradient penalty that generates 64 × 64 anime faces. Try generating one in your browser.", stack: "TensorFlow · NumPy · PIL · Matplotlib", action: "gan" },
  { title: "Image Segmentation", url: "https://github.com/Cynamide/Image-Segmentation", description: "An image segmentation model built using U-Net and a MobileNetV2 encoder to produce masks from input images.", stack: "TensorFlow · NumPy · Matplotlib", action: "segmentation" },
  { title: "Lunar Lander", url: "https://github.com/Cynamide/Lunar-lander", description: "A deep Q-learning agent trained to land in the LunarLander simulation with experience replay and epsilon-greedy exploration.", stack: "TensorFlow · NumPy · OpenAI Gym", action: "lander" },
  { title: "NFT Minting Platform", url: "https://github.com/Cynamide/minting-svelte", description: "A platform built with Candy Machine V2 for minting NFTs on Solana, with artwork generated by an AI model.", stack: "Svelte · Solana · TypeScript", demo: "https://minting-svelte.netlify.app" },
];

export const Projects = () => {
  const [modal, setModal] = useState(null);
  const [isLoading, setIsLoading] = useState(false);
  const [image, setImage] = useState(null);
  const [model, setModel] = useState(null);
  const [generationError, setGenerationError] = useState("");
  const close = () => setModal(null);
  const genImage = async () => {
    setIsLoading(true); setGenerationError("");
    try {
      const loadedModel = model || await tf.loadLayersModel("/tfjs/gan/model.json");
      if (!model) setModel(loadedModel);
      setImage(tf.tidy(() => loadedModel.predict(tf.randomNormal([1, 1, 1, 128])).reshape([64, 64, 3]).arraySync()));
    } catch (error) { setGenerationError("The model could not be loaded. Please try again."); }
    finally { setIsLoading(false); }
  };
  useEffect(() => {
    if (!image || modal !== "gan") return;
    const canvas = document.querySelector(".canvas");
    if (!canvas) return;
    const ctx = canvas.getContext("2d");
    for (let y = 0; y < 64; y++) for (let x = 0; x < 64; x++) {
      const [r, g, b] = image[y][x].map((v) => Math.max(0, Math.min(255, Math.round((v + 1) * 127.5))));
      ctx.fillStyle = `rgb(${r},${g},${b})`; ctx.fillRect(x, y, 1, 1);
    }
  }, [image, modal]);
  return (
    <section id="projects" className="projects-section" aria-labelledby="projects-heading">
      <h1 id="projects-heading" className="projects-heading" data-aos="fade-up" data-aos-once><b>Projects</b></h1>
      <div className="projects-grid">
        {projects.map((project) => (
          <Card key={project.title} className="project-card" data-aos="fade-up" data-aos-once bordered={false} hoverable title={project.title} extra={<a href={project.url} target="_blank" rel="noreferrer">GitHub</a>}>
            <p className="project-description">{project.description}</p>
            <p className="project-stack">{project.stack}</p>
            <div className="project-action">
              {project.demo && <Button type="primary" shape="round" href={project.demo} target="_blank" rel="noreferrer">{project.title === "NFT Minting Platform" ? "Visit the website!" : "Try the live demo"}</Button>}
              {project.action && <Button type="primary" shape="round" onClick={() => setModal(project.action)}>{project.action === "gan" ? "Try it out!" : "See it in action!"}</Button>}
            </div>
          </Card>
        ))}
      </div>
      <Modal title="Create your own Anime Face" visible={modal === "gan"} onCancel={close} footer={[<Button key="cancel" onClick={close}>Cancel</Button>, <Button key="create" type="primary" loading={isLoading} onClick={genImage}>Create</Button>]}>
        <p>Click on create! It may take some time the first time you click.</p>
        {generationError && <p role="alert">{generationError}</p>}
        {image && <canvas className="canvas" height="64" width="64" aria-label="Generated anime face" />}
      </Modal>
      <Modal title="Customer Detection demonstration" visible={modal === "customer"} onCancel={close} width={1000} footer={<Button onClick={close}>Cancel</Button>} destroyOnClose>
        <video width="100%" controls preload="metadata"><source src="/videos/customer-detection.mp4" type="video/mp4" />Your browser does not support video.</video>
      </Modal>
      <Modal title="Image Segmentation demonstration" visible={modal === "segmentation"} onCancel={close} width={1000} footer={<Button onClick={close}>Cancel</Button>} destroyOnClose>
        <video width="100%" controls preload="metadata"><source src="/videos/image-segmentation.mp4" type="video/mp4" />Your browser does not support video.</video>
      </Modal>
      <Modal title="Game example" visible={modal === "rl"} onCancel={close} width={1000} footer={<Button onClick={close}>Cancel</Button>} destroyOnClose>
        <video width="100%" controls><source src="/videos/rl_games.webm" type="video/webm" />Your browser does not support video.</video>
      </Modal>
      <Modal title="Video example" visible={modal === "lander"} onCancel={close} width={800} footer={<Button onClick={close}>Cancel</Button>} destroyOnClose>
        <video width="100%" controls><source src="/videos/lander.webm" type="video/webm" />Your browser does not support video.</video>
      </Modal>
    </section>
  );
};
